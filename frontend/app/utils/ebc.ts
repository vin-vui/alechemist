const MIN_EBC = Math.min(...Object.keys(EBC_HEX).map(Number))
const MAX_EBC = Math.max(...Object.keys(EBC_HEX).map(Number))

export function ebcToHex(ebc: number | string | null): string {
  const n = Math.round(Number(ebc ?? MIN_EBC))
  const clamped = Math.min(MAX_EBC, Math.max(MIN_EBC, Number.isFinite(n) ? n : MIN_EBC))
  // Si un N intermediaire manque dans l'echelle source, prendre le plus proche en dessous.
  for (let i = clamped; i >= MIN_EBC; i--) {
    const hex = EBC_HEX[i]
    if (hex) return hex
  }
  return EBC_HEX[MIN_EBC] as string
}
